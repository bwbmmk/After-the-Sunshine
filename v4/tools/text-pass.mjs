/* ── 括号感知的参数切分 ─────────────────────────────────────────── */
function parseArgs(s, open) {
  let i = open + 1, depth = 1, args = [], start = i;
  while (i < s.length) {
    const c = s[i];
    if (c === "'" || c === '"') {
      const q = c; i++;
      while (i < s.length) { if (s[i] === '\\') i += 2; else if (s[i] === q) { i++; break; } else i++; }
      continue;
    }
    if (c === '`') { i++; while (i < s.length) { if (s[i] === '\\') i += 2; else if (s[i] === '`') { i++; break; } else i++; } continue; }
    if (c === '/' && s[i + 1] === '/') { const nl = s.indexOf('\n', i); i = nl < 0 ? s.length : nl; continue; }
    if (c === '/' && s[i + 1] === '*') { const e = s.indexOf('*/', i + 2); i = e < 0 ? s.length : e + 2; continue; }
    if (c === '(' || c === '[' || c === '{') { depth++; i++; continue; }
    if (c === ')' || c === ']' || c === '}') {
      depth--;
      if (depth === 0) { args.push([start, i]); return { args, end: i + 1 }; }
      i++; continue;
    }
    if (c === ',' && depth === 1) { args.push([start, i]); i++; start = i; continue; }
    i++;
  }
  return null;
}

const calls = [];
const re = /(?:^|\n)(beat|ask)\(/g;
let m;
while ((m = re.exec(src))) {
  const open = m.index + m[0].length - 1;
  const p = parseArgs(src, open);
  if (!p) { console.error('解析失败 @', m.index); continue; }
  const raw = (a) => src.slice(a[0], a[1]).trim();
  const fn = m[1];
  const id = raw(p.args[0]).replace(/^'|'$/g, '');
  calls.push({ fn, id, args: p.args, open });
  re.lastIndex = p.end;
}

const seen = new Set();
const edits = [];
for (const c of calls) {
  if (!NEW[c.id]) continue;
  seen.add(c.id);
  const slot = c.fn === 'beat' ? 2 : 1;
  const a = c.args[slot];
  if (!a) { console.error('缺少文本参数:', c.id); continue; }
  edits.push({ start: a[0], end: a[1], text: NEW[c.id], id: c.id });
}

