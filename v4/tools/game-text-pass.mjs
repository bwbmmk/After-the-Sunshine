/** 找到 `const NAME = {` 里那对大括号的范围 */
function blockRange(s, marker) {
  const at = s.indexOf(marker);
  if (at < 0) throw new Error('找不到 ' + marker);
  const open = s.indexOf('{', at);
  let depth = 0, i = open;
  for (; i < s.length; i++) {
    const c = s[i];
    if (c === "'" || c === '"') {
      const q = c; i++;
      while (i < s.length) { if (s[i] === '\\') i += 2; else if (s[i] === q) break; else i++; }
      continue;
    }
    if (c === '/' && s[i + 1] === '/') { const nl = s.indexOf('\n', i); i = nl < 0 ? s.length : nl; continue; }
    if (c === '{' || c === '[' || c === '(') { depth++; continue; }
    if (c === '}' || c === ']' || c === ')') { depth--; if (depth === 0) return [open, i]; }
  }
  throw new Error('大括号不配对：' + marker);
}

